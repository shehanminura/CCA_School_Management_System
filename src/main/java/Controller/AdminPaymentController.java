package Controller;

import ExcelExportConnection.ExcelExportService;
import Model.dao.AdminPaymentDAO;
import Model.dto.PaymentDto;
import Model.entity.PaymentEntity;
import PdfExportConnection.PdfExportConnection;
import View.AdminAddPaymentPanel;
import java.util.ArrayList;
import javax.swing.JOptionPane;
import javax.swing.table.DefaultTableModel;
import java.util.List;

public class AdminPaymentController {
    private AdminAddPaymentPanel view;
    private AdminPaymentDAO dao;

    public AdminPaymentController(AdminAddPaymentPanel view) {
        this.view = view;
        this.dao = new AdminPaymentDAO();
        loadAutoGeneratedId();
        loadTableData();
        loadStudentsToComboBox();
        loadClassesToComboBox();
    }

    public void loadAutoGeneratedId() {
        view.setPaymentId(dao.generateNextStatusId());
    }

    public void addPayment() {
        String studentId = view.getSelectedStudentId();
        String className = view.getSelectedClassName(); 
        String feeStatus = view.getSelectedFeeStatus();
        String remark = view.getRemark();
        // DateandTimeConnection එකෙන් එන දිනය පමණක් ලබා ගැනීම
        String date = view.getCurrentDate(); 
        if (date != null && date.length() > 10) {
            date = date.substring(0, 10);
        }
        
        String statusId = view.getPaymentIdText();

        if (studentId.isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please select Student ID!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String classId = dao.getClassIdByName(className);

        PaymentEntity entity = new PaymentEntity(statusId, studentId, classId, feeStatus, remark, date);
        if (dao.addPaymentStatus(entity)) {
            JOptionPane.showMessageDialog(view, "Payment Status Added Successfully!");
            view.clearFields();
            loadAutoGeneratedId();
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(view, "Failed to Add Payment Status!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void searchPayment() {
        String studentId = view.getSearchId();
        if (studentId == null || studentId.trim().isEmpty()) {
            studentId = view.getSelectedStudentId(); 
        }

        if (studentId == null || studentId.trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please enter or select a Student ID to search!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PaymentDto dto = dao.searchPayment(studentId.trim());
        if (dto != null) {
            view.setPaymentStatusData(dto);
            JOptionPane.showMessageDialog(view, "Record Found!");
        } else {
            JOptionPane.showMessageDialog(view, "Record Not Found!", "Info", JOptionPane.WARNING_MESSAGE);
        }
    }

    public void updatePayment() {
        String studentId = view.getSearchId();
        if (studentId.trim().isEmpty()) {
            studentId = view.getSelectedStudentId(); 
        }
        
        String className = view.getSelectedClassName();
        String classId = dao.getClassIdByName(className);
        String feeStatus = view.getSelectedFeeStatus();
        String remark = view.getRemark();
        
        String date = view.getCurrentDate();
        if (date != null && date.length() > 10) {
            date = date.substring(0, 10);
        }

        PaymentEntity entity = new PaymentEntity("", studentId, classId, feeStatus, remark, date);
        if (dao.updatePaymentStatus(entity)) {
            JOptionPane.showMessageDialog(view, "Payment Status Updated Successfully!");
            view.clearFields();
            loadAutoGeneratedId();
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(view, "Update Failed!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void deletePayment() {
        String studentId = view.getSearchId();
        if (studentId.trim().isEmpty()) {
            studentId = view.getSelectedStudentId();
        }

        if (studentId.trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please select or search a Student ID to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(view, "Are you sure you want to delete payment records for this student?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (dao.deletePayment(studentId.trim())) {
                JOptionPane.showMessageDialog(view, "Payment Records Deleted Successfully!");
                view.clearFields();
                loadAutoGeneratedId();
                loadTableData();
            } else {
                JOptionPane.showMessageDialog(view, "Delete Failed!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    public void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) view.getTable().getModel();
        model.setRowCount(0);
        model.setColumnIdentifiers(new Object[]{"Status ID", "Student ID", "Student Name", "Class Name", "Fee Status", "Remark", "Date"});

        List<PaymentDto> dataList = dao.getAllPaymentTableData();
        for (PaymentDto dto : dataList) {
            model.addRow(new Object[]{
                dto.getStatusId(),
                dto.getStudentId(),
                dto.getStudentName(),
                dto.getClassName(),
                dto.getFeeStatus(),
                dto.getRemark(),
                dto.getUpdatedDate() 
            });
        }
    }

    public void loadStudentsToComboBox() {
        List<String> students = dao.getStudentIds();
        view.getStudentComboBox().removeAllItems();
        for (String s : students) {
            view.getStudentComboBox().addItem(s);
        }
    }

    public void loadClassesToComboBox() {
        List<String> classes = dao.getClassNames();
        view.getClassComboBox().removeAllItems();
        for (String c : classes) {
            view.getClassComboBox().addItem(c);
        }
    }

// Excel (CSV) Report Export Function
    public void exportToExcel() {
        String headers = "Status ID,Student ID,Student Name,Class Name,Fee Status,Remark,Date";
        List<String> dataRows = new ArrayList<>();
        
        List<PaymentDto> list = dao.getAllPaymentTableData();
        for (PaymentDto dto : list) {
            String row = dto.getStatusId() + "," +
                         dto.getStudentId() + "," +
                         "\"" + dto.getStudentName() + "\"," +
                         "\"" + dto.getClassName() + "\"," +
                         dto.getFeeStatus() + "," +
                         "\"" + dto.getRemark() + "\"," +
                         dto.getUpdatedDate();
            dataRows.add(row);
        }
        
        ExcelExportService.exportToCSV(view, "Payment_Report.csv", headers, dataRows);
    }

    // Professional PDF Report Export Function (HTML based)
    public void exportToPDF() {
        StringBuilder htmlBuilder = new StringBuilder();
        htmlBuilder.append("<!DOCTYPE html>");
        htmlBuilder.append("<html><head><style>")
                   .append("body { font-family: Helvetica, Arial, sans-serif; color: #333333; margin: 15px; } ")
                   .append("table { width: 100%; border-collapse: collapse; font-size: 11px; margin-top: 15px; } ")
                   .append("th { background-color: #006B3C; color: #ffffff; padding: 10px; border: 1px solid #005530; text-align: left; } ")
                   .append("td { padding: 8px; border: 1px solid #dddddd; } ")
                   .append(".even-row { background-color: #F5F9F6; } ")
                   .append(".odd-row { background-color: #ffffff; } ")
                   .append(".status-paid { color: #008000; font-weight: bold; } ")
                   .append(".status-notpaid { color: #d9534f; font-weight: bold; } ")
                   .append(".status-exempted { color: #f0ad4e; font-weight: bold; } ")
                   .append("</style></head><body>");
        
        // Header Section
        htmlBuilder.append("<div style='text-align: center; margin-bottom: 20px;'>");
        htmlBuilder.append("<img src='https://anucentralcollege.com/og-image.jpg' width='75' height='75' />");
        htmlBuilder.append("<h1 style='color: #006B3C; margin: 8px 0 2px 0; font-size: 22px; letter-spacing: 1px;'>")
                   .append("CENTRAL COLLEGE ANURADHAPURA</h1>");
        htmlBuilder.append("<h3 style='color: #666666; margin: 0; font-size: 13px; text-transform: uppercase;'>")
                   .append("Official Student Fee Payment Status Report</h3>");
        htmlBuilder.append("<hr style='border: 0; border-bottom: 2px solid #D4AF37; margin-top: 12px;' />");
        htmlBuilder.append("</div>");
        
        // Table Headers
        htmlBuilder.append("<table>");
        htmlBuilder.append("<tr>")
                   .append("<th>Status ID</th>")
                   .append("<th>Student ID</th>")
                   .append("<th>Student Name</th>")
                   .append("<th>Class Name</th>")
                   .append("<th>Fee Status</th>")
                   .append("<th>Remark</th>")
                   .append("<th>Date</th>")
                   .append("</tr>");

        List<PaymentDto> list = dao.getAllPaymentTableData();
        boolean isEvenRow = false;
        
        for (PaymentDto dto : list) {
            String rowClass = isEvenRow ? "even-row" : "odd-row";
            htmlBuilder.append("<tr class='").append(rowClass).append("'>");
            
            htmlBuilder.append("<td style='color: #B02A37; font-weight: bold;'>").append(dto.getStatusId()).append("</td>");
            htmlBuilder.append("<td>").append(dto.getStudentId()).append("</td>");
            htmlBuilder.append("<td>").append(dto.getStudentName()).append("</td>");
            htmlBuilder.append("<td>").append(dto.getClassName()).append("</td>");
            
            // Payment Status add CSS Class
            String status = dto.getFeeStatus() != null ? dto.getFeeStatus() : "Not Paid";
            String statusClass = "status-notpaid";
            if (status.equalsIgnoreCase("Paid")) {
                statusClass = "status-paid";
            } else if (status.equalsIgnoreCase("Exempted")) {
                statusClass = "status-exempted";
            }
            
            htmlBuilder.append("<td class='").append(statusClass).append("'>").append(status).append("</td>");
            htmlBuilder.append("<td>").append(dto.getRemark() != null ? dto.getRemark() : "-").append("</td>");
            htmlBuilder.append("<td>").append(dto.getUpdatedDate()).append("</td>");
            htmlBuilder.append("</tr>");
            
            isEvenRow = !isEvenRow;
        }
        
        htmlBuilder.append("</table>");
        
        // Official Notification Box
        htmlBuilder.append("<div style='margin-top: 20px; padding: 10px 12px; background-color: #F8F9FA; border-left: 4px solid #006B3C;'>");
        htmlBuilder.append("<p style='font-size: 10px; color: #444444; margin: 0; line-height: 1.5;'>");
        htmlBuilder.append("<strong style='color: #006B3C;'>OFFICIAL SYSTEM NOTIFICATION:</strong><br/>");
        htmlBuilder.append("This is a computer-generated official payment status report produced by the Central College Anuradhapura School Management System. ");
        htmlBuilder.append("As an electronically generated document, it does not require a physical signature or stamp for validation.");
        htmlBuilder.append("</p>");
        htmlBuilder.append("</div>");
        
        // Footer Generation Date
        String currentdate = DateandTimeConnection.DateandTimeConnection.getInstance().getCurrentDate();
        
        htmlBuilder.append("<div style='margin-top: 25px; border-top: 1px solid #eeeeee; padding-top: 8px; text-align: center;'>");
        htmlBuilder.append("<p style='font-size: 9px; color: #888888; margin: 0;'>");
        htmlBuilder.append("Generated by Central College Anuradhapura Management System | Date: " + currentdate);
        htmlBuilder.append("</p>");
        htmlBuilder.append("</div>");
        
        htmlBuilder.append("</body></html>");
        
        // 🔴 මෙතන තමයි Error එක තිබුණේ - .exp. අයින් කරලා නිවැරදි කළා
        PdfExportConnection.getInstance().exportHTMLtoPDF(
            view, 
            "Payment_Status_Report.pdf", 
            htmlBuilder.toString()
        );
    }
}