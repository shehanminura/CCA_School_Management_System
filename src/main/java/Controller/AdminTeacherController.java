    // EXCEL (CSV) Report Generate කිරීම
    // ==============================================
    public void exportToExcel() {
        // 1. Excel (CSV) එකේ මාතෘකා ටික (Headers)
        String headers = "Teacher ID,Full Name,NIC,Birthday,Contact Number,Email,Address,Gender,Salary,Status,Reg. Date";
        
        // 2. දත්ත පේළි (Rows) එකතු කිරීමට List එකක් සෑදීම
        java.util.List<String> dataRows = new java.util.ArrayList<>();
        java.util.List<TeacherEntity> teachers = dao.getAllTeachers();
        
        for (TeacherEntity t : teachers) {
            // Address එකේ කොමා (,) තිබුණොත් CSV එක කැඩෙන නිසා ඒවා Space එකකට මාරු කරනවා
            String safeAddress = t.getAddress() != null ? t.getAddress().replace(",", " ") : "";
            
            String row = t.getTeacherId() + "," +
                         t.getName() + "," +
                         t.getNic() + "," +
                         t.getBirthday() + "," +
                         t.getContactNumber() + "," +
                         t.getEmail() + "," +
                         safeAddress + "," +
                         t.getGender() + "," +
                         t.getSalary() + "," +
                         t.getStatus() + "," +
                         t.getRegistrationDate();
                         
            dataRows.add(row);
        }
        
        // 3. ඔයාගේ Export Connection එකට දත්ත යැවීම
        String defaultFileName = "Teachers_Official_Report.csv";
        ExcelExportConnection.ExcelExportService.exportToCSV(view, defaultFileName, headers, dataRows);
    }
    
