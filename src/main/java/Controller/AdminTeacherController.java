    // Validation Method for Date
    private boolean isValidDate(String date) {
        if (!date.matches("^\\d{4}-\\d{2}-\\d{2}$")) return false;
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        sdf.setLenient(false);
        try { sdf.parse(date); return true; } 
        catch (ParseException e) { return false; }
    }

    public void addTeacher() {
        TeacherDto dto = view.getTeacherData();
        
        // Empty Check
        if (dto.getName().trim().isEmpty() || dto.getNic().trim().isEmpty() || 
            dto.getBirthday().trim().isEmpty() || dto.getContactNumber().trim().isEmpty() || 
            dto.getEmail().trim().isEmpty() || dto.getAddress().trim().isEmpty() || 
            dto.getSalary().trim().isEmpty() || dto.getPassword().trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please fill in all the required fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return; 
        }

        // Field Validations
        if (!dto.getName().matches("^[a-zA-Z\\s]+$")) {
            JOptionPane.showMessageDialog(view, "Invalid Name!", "Error", JOptionPane.ERROR_MESSAGE); return;
        }
        if (!isValidDate(dto.getBirthday())) {
            JOptionPane.showMessageDialog(view, "Invalid Birthday! Use YYYY-MM-DD", "Error", JOptionPane.ERROR_MESSAGE); return;
        }
        if (!dto.getContactNumber().matches("^\\d{10}$")) {
            JOptionPane.showMessageDialog(view, "Invalid Contact Number!", "Error", JOptionPane.ERROR_MESSAGE); return;
        }
        if (!dto.getEmail().matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            JOptionPane.showMessageDialog(view, "Invalid Email!", "Error", JOptionPane.ERROR_MESSAGE); return;
        }
        
        // Validate Salary Number
        double salaryVal = 0.0;
        try {
            salaryVal = Double.parseDouble(dto.getSalary());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(view, "Invalid Salary Amount!", "Error", JOptionPane.ERROR_MESSAGE); return;
        }

        TeacherEntity entity = new TeacherEntity(
            dto.getTeacherId(), dto.getName(), dto.getNic(), dto.getBirthday(), dto.getContactNumber(), 
            dto.getEmail(), dto.getAddress(), dto.getGender(), salaryVal, dto.getPassword(), dto.getStatus()
        );
        
        if (dao.addTeacher(entity)) {
            JOptionPane.showMessageDialog(view, "Teacher Added Successfully!");
            new Thread(() -> AddTeacherEmailService.sendWelcomeEmail(dto)).start();
            view.clearFields();
            view.loadAutoGeneratedId(); 
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(view, "Failed to Add! Email or NIC might already exist.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void loadTableData() {
        List<TeacherEntity> teachers = dao.getAllTeachers();
        DefaultTableModel model = (DefaultTableModel) view.getTable().getModel();
        model.setRowCount(0); 
        
        model.setColumnIdentifiers(new Object[]{"Teacher ID", "Name", "NIC", "Contact", "Email", "Salary", "Status"});
        for (TeacherEntity t : teachers) {
            model.addRow(new Object[]{
                t.getTeacherId(), t.getName(), t.getNic(), t.getContactNumber(), t.getEmail(), t.getSalary(), t.getStatus()
            });
        }
    }

    public void searchTeacher() {
        String searchId = view.getSearchId(); 
        if (searchId == null || searchId.trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please enter a Teacher ID!", "Warning", JOptionPane.WARNING_MESSAGE); return;
        }
        
        TeacherEntity teacher = dao.searchTeacher(searchId.trim()); 
        if (teacher != null) {
            TeacherDto dto = new TeacherDto(
                teacher.getTeacherId(), teacher.getName(), teacher.getNic(), teacher.getBirthday(), teacher.getContactNumber(),
                teacher.getEmail(), teacher.getAddress(), teacher.getGender(), String.valueOf(teacher.getSalary()), teacher.getPassword(), teacher.getStatus()
            );
            view.setTeacherData(dto); 
            JOptionPane.showMessageDialog(view, "Teacher Record Found!");
        } else {
            JOptionPane.showMessageDialog(view, "Teacher Not Found!", "Error", JOptionPane.ERROR_MESSAGE);
            view.clearFields();
            view.loadAutoGeneratedId(); 
        }
    }

    public void updateTeacher() {
        TeacherDto dto = view.getTeacherData();
        
        double salaryVal = 0.0;
        try { salaryVal = Double.parseDouble(dto.getSalary()); } 
        catch (NumberFormatException e) { JOptionPane.showMessageDialog(view, "Invalid Salary Amount!"); return; }

        TeacherEntity entity = new TeacherEntity(
            dto.getTeacherId(), dto.getName(), dto.getNic(), dto.getBirthday(), dto.getContactNumber(), 
            dto.getEmail(), dto.getAddress(), dto.getGender(), salaryVal, dto.getPassword(), dto.getStatus()
        );
        
        if (dao.updateTeacher(entity)) {
            JOptionPane.showMessageDialog(view, "Teacher Updated Successfully!");
            new Thread(() -> AddTeacherEmailService.sendUpdateEmail(dto)).start();
            view.clearFields();
            view.loadAutoGeneratedId();
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(view, "Update Failed!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void deleteTeacher() {
        String teacherId = view.getTeacherData().getTeacherId();
        TeacherEntity teacher = dao.searchTeacher(teacherId);
        
        if (teacher == null) {
            JOptionPane.showMessageDialog(view, "Teacher Not Found to Delete!", "Error", JOptionPane.ERROR_MESSAGE); return;
        }

        int confirm = JOptionPane.showConfirmDialog(view, "Are you sure you want to delete this teacher?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (dao.deleteTeacher(teacherId)) {
                JOptionPane.showMessageDialog(view, "Teacher Deleted Successfully!");
                new Thread(() -> AddTeacherEmailService.sendDeleteEmail(teacher.getEmail(), teacher.getName(), teacherId)).start();
                view.clearFields();
                view.loadAutoGeneratedId();
                loadTableData();
            } else {
                JOptionPane.showMessageDialog(view, "Delete Failed!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }
