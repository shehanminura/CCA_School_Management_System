package Controller;

import Model.dao.AdminSubjectDAO;
import Model.dao.AssignmentDAO;
import Model.dto.AssignmentDto;
import Model.entity.AssignmentEntity;
import Model.entity.SubjectEntity;
import View.AssignmentPanel;
import java.util.List;
import javax.swing.JOptionPane;
import javax.swing.table.DefaultTableModel;

public class AssignmentController {

    private final AssignmentPanel view;
    private final AssignmentDAO dao;
    private final AdminSubjectDAO subjectDao;

    public AssignmentController(AssignmentPanel view) {
        this.view = view;
        this.dao = new AssignmentDAO();
        this.subjectDao = new AdminSubjectDAO();
    }

    // Database එකේ ඇති සියලු Subject IDs ComboBox එකට දැමීම
    public void loadSubjectIds() {
        try {
            List<SubjectEntity> subjects = subjectDao.getAllSubjects();
            view.getSubjectComboBox().removeAllItems();
            view.getSubjectComboBox().addItem("-- Select Subject --");
            for (SubjectEntity sub : subjects) {
                view.getSubjectComboBox().addItem(sub.getSubjectId());
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    // Table එකට Assignments Load කිරීම
    public void loadTableData() {
        try {
            List<AssignmentEntity> list = dao.getAllAssignments();
            String[] columns = {"Assignment ID", "Subject ID", "Title", "Due Date", "Link", "Description"};
            DefaultTableModel model = new DefaultTableModel(columns, 0) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false;
                }
            };

            for (AssignmentEntity a : list) {
                model.addRow(new Object[]{
                    a.getAssignmentId(),
                    a.getSubjectId(),
                    a.getTitle(),
                    a.getDueDate(),
                    a.getAssignmentLink(),
                    a.getDescription()
                });
            }
            view.getTable().setModel(model);
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void addAssignment() {
        try {
            AssignmentDto dto = view.getAssignmentData();
            if (dto.getSubjectId().equals("Select Subject") || dto.getTitle().isEmpty() || dto.getAssignmentLink().isEmpty()) {
                JOptionPane.showMessageDialog(view, "Please fill in all required fields!");
                return;
            }

            AssignmentEntity entity = new AssignmentEntity(
                dto.getAssignmentId(),
                dto.getSubjectId(),
                dto.getTitle(),
                dto.getDescription(),
                dto.getAssignmentLink(),
                dto.getDueDate()
            );

            if (dao.addAssignment(entity)) {
                JOptionPane.showMessageDialog(view, "Assignment added successfully!");
                loadTableData();
                view.clearFields();
                view.loadAutoGeneratedId();
            } else {
                JOptionPane.showMessageDialog(view, "Failed to add Assignment!");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void deleteAssignment() {
        try {
            String id = view.getAssignmentData().getAssignmentId();
            // AssignmentDAO එකට delete ක්‍රමය අවශ්‍ය නම්
            String query = "DELETE FROM assignment WHERE assignment_id = ?";
            java.sql.Connection con = DBConnection.DBConnection.getInstance().getConnection();
            try (java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                pst.setString(1, id);
                if (pst.executeUpdate() > 0) {
                    JOptionPane.showMessageDialog(view, "Assignment deleted successfully!");
                    loadTableData();
                    view.clearFields();
                    view.loadAutoGeneratedId();
                } else {
                    JOptionPane.showMessageDialog(view, "Assignment ID not found!");
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void updateAssignment() {
        try {
            AssignmentDto dto = view.getAssignmentData();
            String query = "UPDATE assignment SET subject_id=?, title=?, description=?, assignment_link=?, due_date=? WHERE assignment_id=?";
            java.sql.Connection con = DBConnection.DBConnection.getInstance().getConnection();
            try (java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                pst.setString(1, dto.getSubjectId());
                pst.setString(2, dto.getTitle());
                pst.setString(3, dto.getDescription());
                pst.setString(4, dto.getAssignmentLink());
                pst.setString(5, dto.getDueDate());
                pst.setString(6, dto.getAssignmentId());

                if (pst.executeUpdate() > 0) {
                    JOptionPane.showMessageDialog(view, "Assignment updated successfully!");
                    loadTableData();
                    view.clearFields();
                    view.loadAutoGeneratedId();
                } else {
                    JOptionPane.showMessageDialog(view, "Failed to update Assignment!");
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public void searchAssignment() {
        try {
            String searchId = view.getSearchId().trim();
            String query = "SELECT * FROM assignment WHERE assignment_id = ?";
            java.sql.Connection con = DBConnection.DBConnection.getInstance().getConnection();
            try (java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                pst.setString(1, searchId);
                try (java.sql.ResultSet rst = pst.executeQuery()) {
                    if (rst.next()) {
                        AssignmentDto dto = new AssignmentDto(
                            rst.getString("assignment_id"),
                            rst.getString("subject_id"),
                            rst.getString("title"),
                            rst.getString("description"),
                            rst.getString("assignment_link"),
                            rst.getString("due_date")
                        );
                        view.setAssignmentData(dto);
                    } else {
                        JOptionPane.showMessageDialog(view, "Assignment not found!");
                    }
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
}
