package Controller;

import Model.dao.AdminSubjectDAO;
import Model.dto.SubjectDto;
import Model.entity.SubjectEntity;
import View.AdminAddSubjectPanel;
import java.util.List;
import javax.swing.JOptionPane;
import javax.swing.table.DefaultTableModel;

public class AdminSubjectController {

    private AdminAddSubjectPanel view;
    private AdminSubjectDAO dao;

    public AdminSubjectController(AdminAddSubjectPanel view) {
        this.view = view;
        try {
            this.dao = new AdminSubjectDAO();
            loadTableData();
        } catch (Exception e) { System.out.println("Admin Subject Controller Load Error: " + e.getMessage()); }
    }

    public void addSubject() {
        SubjectDto dto = view.getSubjectData();

        if (dto.getSubjectName().trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Please enter the subject name!", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        SubjectEntity entity = new SubjectEntity(dto.getSubjectId(), dto.getSubjectName());

        if (dao.addSubject(entity)) {
            JOptionPane.showMessageDialog(view, "Subject Added Successfully!");
            view.clearFields();
            view.loadAutoGeneratedId();
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(view, "Failed to Add Subject! Subject ID might already exist.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void loadTableData() {
        List<SubjectEntity> subjects = dao.getAllSubjects();
        DefaultTableModel model = (DefaultTableModel) view.getTable().getModel();
        model.setRowCount(0);
        model.setColumnIdentifiers(new Object[]{"Subject ID", "Subject Name"});
        
        for (SubjectEntity s : subjects) {
            model.addRow(new Object[]{ s.getSubjectId(), s.getSubjectName() });
        }
    }

    public void searchSubject() {
        String searchId = view.getSearchId();
        if (searchId == null || searchId.trim().isEmpty()) { 
            JOptionPane.showMessageDialog(view, "Please enter a Subject ID!"); 
            return; 
        }

        SubjectEntity subjectEntity = dao.searchSubject(searchId.trim());
        if (subjectEntity != null) {
            SubjectDto dto = new SubjectDto(subjectEntity.getSubjectId(), subjectEntity.getSubjectName());
            view.setSubjectData(dto);
            JOptionPane.showMessageDialog(view, "Subject Record Found!");
        } else {
            JOptionPane.showMessageDialog(view, "Subject Not Found!", "Error", JOptionPane.ERROR_MESSAGE);
            view.clearFields(); 
            view.loadAutoGeneratedId();
        }
    }

    public void updateSubject() {
        SubjectDto dto = view.getSubjectData();
        if (dto.getSubjectName().trim().isEmpty()) {
            JOptionPane.showMessageDialog(view, "Subject Name cannot be empty!");
            return;
        }

        SubjectEntity entity = new SubjectEntity(dto.getSubjectId(), dto.getSubjectName());

        if (dao.updateSubject(entity)) {
            JOptionPane.showMessageDialog(view, "Subject Updated Successfully!");
            view.clearFields(); 
            view.loadAutoGeneratedId(); 
            loadTableData();
        } else { 
            JOptionPane.showMessageDialog(view, "Update Failed!", "Error", JOptionPane.ERROR_MESSAGE); 
        }
    }

    public void deleteSubject() {
        String subjectId = view.getSubjectData().getSubjectId();
        SubjectEntity subjectEntity = dao.searchSubject(subjectId);
        if (subjectEntity == null) { 
            JOptionPane.showMessageDialog(view, "Subject Not Found!"); 
            return; 
        }

        int confirm = JOptionPane.showConfirmDialog(view, "Are you sure you want to delete this subject?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            if (dao.deleteSubject(subjectId)) {
                JOptionPane.showMessageDialog(view, "Subject Deleted Successfully!");
                view.clearFields(); 
                view.loadAutoGeneratedId(); 
                loadTableData();
            } else { 
                JOptionPane.showMessageDialog(view, "Delete Failed!", "Error", JOptionPane.ERROR_MESSAGE); 
            }
        }
    }



 
}
