 // 1. Payment Status Chart (chartContainerPanel තුළ)
    public void loadPieChart() {
        if (dashboardController == null) return;
        
        org.jfree.data.general.DefaultPieDataset dataset = dashboardController.createPaymentPieDataset();
        
        JFreeChart chart = ChartFactory.createPieChart(
            "Payment Status Overview", 
            dataset, true, true, false
        );
        
        stylePieChart(chart); // පොදු Styling ලබාදීම
        
        PiePlot plot = (PiePlot) chart.getPlot();
        plot.setSectionPaint("Paid", new Color(16, 185, 129));     // Emerald Green
        plot.setSectionPaint("Not Paid", new Color(239, 68, 68));  // Rose Red
        plot.setSectionPaint("Exempted", new Color(59, 130, 246)); // Royal Blue
        
        addChartToPanel(chart, chartContainerPanel);
    }

    // 2. System Users Chart (userpanel තුළ)
    public void loadUserChart() {
        if (dashboardController == null) return;
        
        org.jfree.data.general.DefaultPieDataset dataset = dashboardController.createUserPieDataset();
        
        JFreeChart chart = ChartFactory.createPieChart(
            "System Users Overview", 
            dataset, true, true, false
        );
        
        stylePieChart(chart); // පොදු Styling ලබාදීම
        
        PiePlot plot = (PiePlot) chart.getPlot();
        plot.setSectionPaint("Student", new Color(59, 130, 246));  // Royal Blue
        plot.setSectionPaint("Teacher", new Color(139, 92, 246));  // Modern Purple
        plot.setSectionPaint("Admin", new Color(245, 158, 11));    // Amber / Orange
        
        // 🔴 ඔබ ඉල්ලූ userpanel variable එකට Chart එක දැමීම
        addChartToPanel(chart, userpanel);
    }

    // --- කෝඩ් එක Repeat වීම වැළැක්වීමට පොදු Styling Methods දෙකක් ---
    private void stylePieChart(JFreeChart chart) {
        chart.setBackgroundPaint(Color.WHITE);
        chart.getTitle().setPaint(new Color(30, 41, 59));
        chart.getTitle().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 14));
        chart.setAntiAlias(true);
        
        PiePlot plot = (PiePlot) chart.getPlot();
        plot.setBackgroundPaint(Color.WHITE);
        plot.setOutlinePaint(null);
        plot.setInteriorGap(0.12);
        plot.setLabelGenerator(new org.jfree.chart.labels.StandardPieSectionLabelGenerator("{0}: {1} ({2})"));
        plot.setLabelFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 11));
        plot.setLabelBackgroundPaint(new Color(255, 255, 255, 220));
        
        if (chart.getLegend() != null) {
            chart.getLegend().setItemFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
            chart.getLegend().setBackgroundPaint(Color.WHITE);
            chart.getLegend().setFrame(org.jfree.chart.block.BlockBorder.NONE);
        }
    }

    private void addChartToPanel(JFreeChart chart, javax.swing.JPanel targetPanel) {
        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setMouseWheelEnabled(true);
        chartPanel.setPreferredSize(new java.awt.Dimension(360, 260));
        
        targetPanel.setLayout(new java.awt.BorderLayout());
        targetPanel.setBackground(Color.WHITE);
        targetPanel.setBorder(javax.swing.BorderFactory.createCompoundBorder(
            javax.swing.BorderFactory.createLineBorder(new Color(226, 232, 240), 1, true),
            javax.swing.BorderFactory.createEmptyBorder(12, 12, 12, 12)
        ));
        
        targetPanel.removeAll();
        targetPanel.add(chartPanel, java.awt.BorderLayout.CENTER);
        targetPanel.revalidate();
        targetPanel.repaint();
    }

  
